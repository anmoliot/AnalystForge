"""Regenerate the endpoint reference from the application's OpenAPI schema."""

import secrets
from pathlib import Path

from analystforge.api.config import Settings
from analystforge.api.main import create_app


def main() -> None:
    settings = Settings(
        _env_file=None,
        environment="test",
        secret_key=secrets.token_hex(32),
        database_url="sqlite+aiosqlite://",
        redis_url=None,
    )
    schema = create_app(settings).openapi()
    intro = """# API reference

Generated by `uv run python scripts/generate_api_docs.py` from the application's OpenAPI schema.
Interactive schemas, request examples and model fields are available at `/docs` and
`/api/v1/openapi.json`. The versioned prefix is `/api/v1`.

## Authentication

Register with `POST /api/v1/auth/register`, then log in with `POST /api/v1/auth/login`.
Send the returned access token as `Authorization: Bearer $TOKEN`. API keys use the same header.
Refresh uses the httpOnly cookie scoped to `/api/v1/auth/refresh` and rotates on use.
Public company, metadata and calculation routes coexist with authenticated user-resource routes.
The current OpenAPI schema describes headers through dependencies and does not declare OAuth scopes.
See SECURITY.md for the current authorization limitations.

## Pagination and errors

There is no universal pagination wrapper. List routes expose their own `limit`, `offset`,
date ranges or filter parameters where implemented. Consult the schema before requesting a large list.
Errors use `{"error":{"code":"...","message":"...","request_id":"..."}}` with optional `details`.
Quote `X-Request-ID` when reporting a failure. Missing analysis data is reported through a null,
an explicit unavailable response or HTTP 422, depending on the endpoint.

## Request quotas

Versioned routes share 240 requests per minute per verified API key/user or anonymous IP.
Authentication writes share 10 requests per minute per IP. Key creation uses the authenticated identity.
Configure `RATE_LIMIT_PER_MINUTE` and `RATE_LIMIT_AUTH_PER_MINUTE`. HTTP 429 uses the error envelope
and includes `Retry-After` seconds and `X-Request-ID`. Probes are outside application quotas.
Redis failure activates per-process quotas, as documented in DECISIONS.md.

## Examples

```bash
curl -fsS http://localhost:8000/api/v1/meta
curl -fsS http://localhost:8000/api/v1/companies/AAPL/statements
curl -fsS -H "Authorization: Bearer $TOKEN" http://localhost:8000/api/v1/portfolios
curl -f -H "Authorization: Bearer $TOKEN" -o report.pdf \
  "http://localhost:8000/api/v1/reports/$REPORT_ID/download?format=PDF"
```

## Endpoints

| Method | Path | Summary | Request model | Parameters |
|---|---|---|---|---|
"""
    rows = []
    for path, item in sorted(schema["paths"].items()):
        for method, operation in item.items():
            if method not in {"get", "post", "put", "patch", "delete", "options", "head"}:
                continue
            body = operation.get("requestBody", {}).get("content", {})
            model = (
                body.get("application/json", {}).get("schema", {}).get("$ref", "").split("/")[-1]
            )
            params = ", ".join(
                p["name"] + " (" + p["in"] + ")" for p in operation.get("parameters", [])
            )
            summary = operation.get("summary", "").replace("|", "/")
            rows.append(f"| {method.upper()} | `{path}` | {summary} | {model} | {params} |")
    Path("docs/API.md").write_text(intro + "\n".join(rows) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
